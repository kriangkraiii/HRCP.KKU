-- V30: เวลาที่ผู้ยื่นกด "ยื่นการแก้ไข" สำหรับเอกสารที่ถูกส่งกลับ
--
-- เอกสารส่วนใหญ่ที่ส่งกลับมีช่องลงนามของผู้ยื่น การลงนามใหม่จึงเท่ากับการยื่นการแก้ไข
-- แต่เอกสารที่ 6 ของคำร้องขอตำแหน่งมีแค่ช่องลงนามของคณบดี ผู้ยื่นแก้แล้วไม่มีทางบอกได้ว่าเสร็จ
-- สถานะ "ต้องแก้ไขเอกสาร" จึงค้างตลอดไป คอลัมน์นี้คือการยื่นของเอกสารกลุ่มนั้น
--
-- การยื่นนับเฉพาะเมื่อ revision_submitted_at อยู่หลัง revision_requested_at ถ้าเจ้าหน้าที่
-- ส่งกลับรอบใหม่ ค่าเก่าจะเก่ากว่าเวลาส่งกลับเอง ไม่ต้องล้างทิ้ง

ALTER TABLE position_document ADD COLUMN IF NOT EXISTS revision_submitted_at TIMESTAMP;
