-- ลบคลังไฟล์ส่วนตัวของผู้ยื่นออกจากระบบ
--
-- ระบบมีคลังไฟล์สองชุดที่เป็นฝาแฝดกัน ฝั่งแอดมิน (admin_file/admin_folder)
-- กับฝั่งผู้ยื่น (user_file/user_folder) ตอนนี้เหลือใช้เฉพาะฝั่งแอดมิน
-- โค้ดฝั่งผู้ยื่นถูกคอมเมนต์ไว้ทั้งชุดแล้ว ตารางจึงไม่มีอะไรอ่านหรือเขียนอีก
--
-- ตอนที่ลบทั้งสองตารางว่างเปล่า ไม่มีข้อมูลผู้ใช้สูญหาย
-- ไฟล์ใน uploads/user-storage/ ถูกลบแยกต่างหาก
--
-- ลำดับการ drop สำคัญ: user_file มี foreign key ชี้ไปที่ user_folder
-- จึงต้อง drop user_file ก่อน ส่วน user_folder มี self-reference (parent_id)
-- ซึ่ง drop ตัวเองได้ในคำสั่งเดียว
--
-- ใช้ IF EXISTS เพราะบนฐานข้อมูลที่ใช้งานอยู่ตอนนี้ทั้งสองตารางถูก drop
-- ด้วยมือไปแล้ว migration นี้จึงเป็น no-op ที่นั่น แต่ยังจำเป็นสำหรับ
-- ฐานข้อมูลเครื่องอื่นที่ยังมีตารางค้างอยู่

DROP TABLE IF EXISTS user_file;
DROP TABLE IF EXISTS user_folder;
